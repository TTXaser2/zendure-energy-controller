class ValueType(Enum):
    INT = "int"
    OPTIONAL_INT = "optional_int"
    FLOAT = "float"
    BOOL = "bool"
    STRING = "string"
    ENUM = "enum"
    TIME_HH_MM = "time_hh_mm"
